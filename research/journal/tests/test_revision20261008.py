def fixed_predictions(bits, pdr=0.95, burst=2.0):
    rows = (len(bits) + 99) // 100
    return pd.DataFrame({
        "PDR": np.full(rows, pdr), "Max_Burst": np.full(rows, burst),
        "Pred_PDR_cons": np.full(rows, pdr),
        "Pred_B_cons": np.full(rows, burst),
    })


class SyntheticChecks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.bsm_lut = revision.ActionTable.from_csv(
            INPUTS / "lut" / "56LUT_3_Balanced.csv", K=8)
        cls.sdsm_lut = revision.ActionTable.from_csv(
            INPUTS / "lut" / "513LUT_3_Balanced.csv", K=27)

    def test_mask_includes_entire_run_at_312_and_not_311(self):
        for length, expected in ((311, False), (312, True), (313, True)):
            with self.subTest(length=length):
                bits = np.r_[np.ones(4), np.zeros(length), np.ones(4)].astype(np.uint8)
                mask = revision.build_skip_mask(bits, threshold=312)
                np.testing.assert_array_equal(mask[:4], False)
                np.testing.assert_array_equal(mask[4:4 + length], expected)
                np.testing.assert_array_equal(mask[4 + length:], False)

    def test_mask_covers_leading_and_trailing_complete_runs(self):
        for bits in (np.r_[np.zeros(312), np.ones(5)],
                     np.r_[np.ones(5), np.zeros(312)]):
            mask = revision.build_skip_mask(bits.astype(np.uint8), threshold=312)
            np.testing.assert_array_equal(mask, bits == 0)

    def test_future_observations_do_not_change_current_or_prior_predictions(self):
        original = pd.DataFrame({
            "PDR": [.90, .88, .92, .89, .91, .80, .84, .82, .90, .85, .86, .88],
            "Max_Burst": [1, 2, 1, 2, 1, 5, 4, 5, 2, 4, 3, 2],
        })
        params = revision.PredictorParameters(
            reset_sigma_p=.2564, reset_sigma_b=18.89)
        columns = ["Pred_PDR_mean", "Pred_B_mean", "Pred_PDR_cons", "Pred_B_cons"]
        for cut in (0, 5, 8):
            changed = original.copy()
            changed.loc[cut:, "PDR"] = .10
            changed.loc[cut:, "Max_Burst"] = 80
            for mode, z in Z_VALUES.items():
                with self.subTest(mode=mode, cut=cut):
                    before = revision.predict_ewma(original, z, params)
                    after = revision.predict_ewma(changed, z, params)
                    # Prediction for row cut may observe only rows before cut.
                    np.testing.assert_array_equal(
                        before.loc[:cut, columns], after.loc[:cut, columns])
                    self.assertFalse(np.array_equal(
                        before.loc[cut + 1:, columns], after.loc[cut + 1:, columns]))
            naive_before = revision.naive_predictions(original)
            naive_after = revision.naive_predictions(changed)
            np.testing.assert_array_equal(
                naive_before.loc[:cut, ["Pred_PDR_cons", "Pred_B_cons"]],
                naive_after.loc[:cut, ["Pred_PDR_cons", "Pred_B_cons"]])

    def test_oracle_is_explicitly_noncausal(self):
        original = pd.DataFrame({"PDR": [.90] * 10, "Max_Burst": [1] * 10})
        changed = original.copy()
        changed.loc[6, ["PDR", "Max_Burst"]] = [.10, 50]
        before = revision.oracle_predictions(original, half_window=2)
        after = revision.oracle_predictions(changed, half_window=2)
        self.assertNotEqual(before.loc[4, "Pred_PDR_cons"], after.loc[4, "Pred_PDR_cons"])
        self.assertNotEqual(before.loc[4, "Pred_B_cons"], after.loc[4, "Pred_B_cons"])

    def test_low_pdr_alone_clamps_and_burst_above_40_saturates(self):
        self.assertEqual(self.bsm_lut.lookup(.10, 40), self.bsm_lut.lookup(.45, 40))
        self.assertEqual(self.sdsm_lut.lookup(.10, 40), self.sdsm_lut.lookup(.45, 40))
        self.assertEqual(self.bsm_lut.lookup(.95, 40.01), (64, 2))
        self.assertEqual(self.sdsm_lut.lookup(.95, 40.01), (140, 1))

    def test_excluded_start_can_recover_and_mask_does_not_cancel_transmission(self):
        bits = np.ones(600, dtype=np.uint8)
        bits[10:322] = 0
        starts = np.array([320, 323], dtype=np.int64)
        mask = revision.build_skip_mask(bits, threshold=312)
        excluded = mask[starts]
        config = revision.ReplayConfig.for_profile("BSM", target_retained=1)
        result = revision.replay(
            bits, fixed_predictions(bits), self.bsm_lut, "ARGUS-B", config,
            offers=(starts, excluded), return_events=True)
        self.assertEqual(result["offered"], 2)
        self.assertEqual(result["excluded"], 1)
        self.assertEqual(result["excluded_successes"], 1)
        self.assertEqual(result["excluded_failures"], 0)
        self.assertEqual(result["retained_failures"], 0)
        events = result["events"]
        np.testing.assert_array_equal(events["starts"], starts)
        self.assertGreater(events["N"][0], 0)
        self.assertTrue(events["success"][0])

    def test_all_schemes_share_offers_and_baseline_resource_units(self):
        bits = np.ones(1000, dtype=np.uint8)
        bits[100:412] = 0
        config = revision.ReplayConfig.for_profile("BSM", target_retained=20)
        offers = revision.generate_offers(bits, config)
        predictions = fixed_predictions(bits)
        for scheme in ("RAW", "REP3", "REP5", "NAIVE", "ARGUS-B", "ORACLE"):
            with self.subTest(scheme=scheme):
                result = revision.replay(
                    bits, predictions, self.bsm_lut, scheme, config,
                    offers=offers, return_events=True)
                np.testing.assert_array_equal(result["events"]["starts"], offers[0])
                np.testing.assert_array_equal(result["events"]["excluded"], offers[1])
                self.assertEqual(result["offered"], len(offers[0]))
                self.assertEqual(result["retained"], 20)
                if scheme in ("RAW", "REP3", "REP5"):
                    copies = {"RAW": 1, "REP3": 3, "REP5": 5}[scheme]
                    self.assertEqual(result["retained_expansion"], copies)
                    self.assertEqual(result["all_offered_expansion"], copies)

    def test_early_recovery_still_accounts_for_all_selected_symbols(self):
        bits = np.ones(400, dtype=np.uint8)
        starts = np.array([0], dtype=np.int64)
        config = revision.ReplayConfig.for_profile("BSM", target_retained=1)
        result = revision.replay(
            bits, fixed_predictions(bits), self.bsm_lut, "ARGUS-B", config,
            offers=(starts, np.array([False])), return_events=True)
        self.assertTrue(result["events"]["success"][0])
        expected_n, _ = self.bsm_lut.lookup(.95, 2)
        self.assertGreater(expected_n, 8)
        self.assertEqual(result["all_offered_expansion"], expected_n / 8)

    def test_kth_received_symbol_at_170_is_in_time_and_after_170_is_not(self):
        config = revision.ReplayConfig.for_profile(
            "SDSM", target_retained=1, spacing_ms=.5)
        starts = np.array([0], dtype=np.int64)
        offers = (starts, np.array([False]))
        for last_offset, expected_success in ((170, True), (172, False)):
            with self.subTest(last_offset=last_offset):
                bits = np.zeros(400, dtype=np.uint8)
                # Saturation (N=140,G=1) sends at even offsets. The first
                # 26 survivors are 118..168; the 27th controls recovery.
                bits[np.arange(118, 170, 2)] = 1
                bits[last_offset] = 1
                result = revision.replay(
                    bits, fixed_predictions(bits, pdr=.40, burst=50),
                    self.sdsm_lut, "ARGUS-R", config,
                    offers=offers, return_events=True)
                self.assertEqual(bool(result["events"]["success"][0]), expected_success)
                self.assertEqual(result["retained_failures"], int(not expected_success))
                self.assertEqual(result["events"]["N"][0], 140)
                # It is the K-th survivor, not the last selected symbol,
                # that must arrive before the deadline.
                self.assertEqual(result["all_offered_expansion"], 140 / 27)


class PublishedRegression(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.bits = {trace: revision.load_trace_bits(INPUTS / trace / "trace.bin")
                    for trace in ("A", "B", "C")}
        cls.predictions = {
            (trace, mode): pd.read_csv(INPUTS / trace / filename)
            for trace in ("A", "B", "C")
            for mode, filename in PREDICTION_FILES.items()
        }
        cls.metrics = {trace: cls.predictions[trace, "ARGUS-C"][["PDR", "Max_Burst"]]
                       for trace in ("A", "B", "C")}
        cls.luts = {
            "BSM": revision.ActionTable.from_csv(INPUTS / "lut" / "56LUT_3_Balanced.csv", K=8),
            "SDSM": revision.ActionTable.from_csv(INPUTS / "lut" / "513LUT_3_Balanced.csv", K=27),
        }
        cls.results = {}
        for trace, profile in CASES:
            config = revision.ReplayConfig.for_profile(profile)
            offers = revision.generate_offers(cls.bits[trace], config)
            for scheme in TABLE_VII:
                if scheme == "NAIVE":
                    predictions = revision.naive_predictions(cls.metrics[trace])
                elif scheme == "ORACLE":
                    predictions = revision.oracle_predictions(cls.metrics[trace])
                else:
                    predictions = cls.predictions[trace, scheme] if scheme in Z_VALUES else None
                cls.results[trace, profile, scheme] = revision.replay(
                    cls.bits[trace], predictions, cls.luts[profile], scheme,
                    config, offers=offers)

    def test_table_vi_exact_accounting(self):
        fields = ("offered", "excluded", "retained_failures",
                  "excluded_failures", "excluded_successes")
        for (trace, profile), expected in TABLE_VI.items():
            scheme = "ARGUS-B" if profile == "BSM" else "ARGUS-R"
            with self.subTest(trace=trace, profile=profile):
                actual = self.results[trace, profile, scheme]
                self.assertEqual(tuple(actual[name] for name in fields), expected)
                self.assertEqual(actual["retained"], 100000)
                self.assertEqual(actual["all_failures"], expected[2] + expected[3])

    def test_table_vii_all_schemes_and_resource_accounting(self):
        for scheme, expected_cells in TABLE_VII.items():
            for (trace, profile), expected in zip(CASES, expected_cells):
                with self.subTest(trace=trace, profile=profile, scheme=scheme):
                    actual = self.results[trace, profile, scheme]
                    offered, excluded, *_ = TABLE_VI[trace, profile]
                    self.assertEqual(actual["offered"], offered)
                    self.assertEqual(actual["excluded"], excluded)
                    self.assertEqual(actual["retained"], 100000)
                    self.assertEqual(actual["retained_failures"], round(expected[0] * 1000))
                    self.assertAlmostEqual(actual["conditional_outage_pct"], expected[0], delta=.000500001)
                    self.assertAlmostEqual(actual["all_offered_outage_pct"], expected[2], delta=.000500001)
                    self.assertAlmostEqual(actual["retained_expansion"], expected[1], delta=.005000001)
                    self.assertAlmostEqual(actual["all_offered_expansion"], expected[3], delta=.005000001)
                    self.assertEqual(actual["excluded_failures"] + actual["excluded_successes"], excluded)
                    self.assertEqual(actual["all_failures"], actual["retained_failures"] + actual["excluded_failures"])

    def test_table_v_published_continuous_coverage(self):
        for mode, expected_values in TABLE_V.items():
            for trace, expected in zip(("A", "B", "C"), expected_values):
                with self.subTest(trace=trace, mode=mode):
                    predictions = (revision.naive_predictions(self.metrics[trace])
                                   if mode == "NAIVE" else self.predictions[trace, mode])
                    actual = revision.prediction_coverage(self.metrics[trace], predictions, warmup=5)
                    self.assertEqual(actual["evaluated_windows"], COVERAGE_WINDOWS[trace])
                    self.assertAlmostEqual(actual["joint_coverage_pct"], expected, delta=.005000001)

    def test_supplementary_table_s4_fixed_lut_half_ms_scenario(self):
        for (trace, profile, scheme), expected in TABLE_S4_HALF_MS.items():
            with self.subTest(trace=trace, profile=profile, scheme=scheme):
                config = revision.ReplayConfig.for_profile(profile, spacing_ms=.5)
                offers = revision.generate_offers(self.bits[trace], config)
                predictions = (revision.oracle_predictions(self.metrics[trace])
                               if scheme == "ORACLE" else self.predictions.get((trace, scheme)))
                actual = revision.replay(
                    self.bits[trace], predictions, self.luts[profile], scheme,
                    config, offers=offers)
                self.assertEqual(actual["deadline_offset"], 170)
                self.assertEqual(actual["offered"], TABLE_VI[trace, profile][0])
                self.assertEqual(actual["excluded"], TABLE_VI[trace, profile][1])
                self.assertAlmostEqual(actual["all_offered_outage_pct"], expected, delta=.000500001)

    def test_generated_predictions_match_released_archive(self):
        reset_p, reset_b = revision.fit_reset_scales(self.metrics["A"], rolling_window=20, quantile=.90)
        # Reconstructed archived execution: A uses its full-precision fitted
        # scales; B/C receive the rounded values reported in manuscript
        # Table III. This is a fixed handoff rule, not fitting B/C data.
        self.assertEqual(round(reset_p, 4), .2564)
        self.assertEqual(round(reset_b, 2), 18.89)
        columns = ["Pred_PDR_cons", "Pred_B_cons"]
        for trace in ("A", "B", "C"):
            params = revision.PredictorParameters(
                reset_sigma_p=reset_p if trace == "A" else .2564,
                reset_sigma_b=reset_b if trace == "A" else 18.89)
            self.assertEqual(
                revision.execution_parameters((reset_p, reset_b), trace), params)
            for mode, z in Z_VALUES.items():
                with self.subTest(trace=trace, mode=mode):
                    generated = revision.predict_ewma(self.metrics[trace], z, params)
                    archived = self.predictions[trace, mode]
                    np.testing.assert_allclose(generated[columns], archived[columns], rtol=0, atol=5e-10)

    def test_shared_full_precision_is_distinct_from_archived_handoff(self):
        reset_p, reset_b = revision.fit_reset_scales(self.metrics["A"], rolling_window=20, quantile=.90)
        params = revision.PredictorParameters(reset_sigma_p=reset_p, reset_sigma_b=reset_b)
        for trace in ("B", "C"):
            self.assertEqual(
                revision.execution_parameters(
                    (reset_p, reset_b), trace, calibration_policy="shared_full_precision"),
                params)
            for mode in ("ARGUS-B", "ARGUS-R", "ARGUS-E"):
                with self.subTest(trace=trace, mode=mode):
                    shared = revision.predict_ewma(self.metrics[trace], Z_VALUES[mode], params)
                    archived = self.predictions[trace, mode]
                    difference = np.abs(shared["Pred_B_cons"] - archived["Pred_B_cons"])
                    # Small numerical differences are real; verification
                    # must not loosen its tolerance to relabel them matches.
                    self.assertGreater(float(difference.max()), .001)

    def test_complete_window_metrics_match_released_trace_bits(self):
        for trace in ("A", "B", "C"):
            with self.subTest(trace=trace):
                rebuilt = revision.window_metrics(self.bits[trace], window=100)
                archived = self.metrics[trace]
                complete = len(self.bits[trace]) // 100
                self.assertEqual(len(rebuilt), len(archived))
                np.testing.assert_allclose(
                    rebuilt.iloc[:complete][["PDR", "Max_Burst"]],
                    archived.iloc[:complete][["PDR", "Max_Burst"]],
                    rtol=0, atol=1e-12)
                # A final partial window is intentionally not forced to
                # match: the paper replay uses the archived CSV truth,
                # whereas window_metrics reports the actual partial bits.

    def test_integer_query_coverage_is_reported_separately(self):
        trace, mode = "A", "ARGUS-R"
        metrics, predictions = self.metrics[trace], self.predictions[trace, mode]
        actual = revision.prediction_coverage(metrics, predictions, warmup=5, integer_query=True)
        retained = slice(5, None)
        pdr_ok = predictions["Pred_PDR_cons"].to_numpy()[retained] <= metrics["PDR"].to_numpy()[retained]
        burst_ok = np.ceil(predictions["Pred_B_cons"].to_numpy()[retained]) >= metrics["Max_Burst"].to_numpy()[retained]
        manual = 100 * np.mean(pdr_ok & burst_ok)
        self.assertAlmostEqual(actual["joint_coverage_pct"], manual, places=10)
        continuous = revision.prediction_coverage(metrics, predictions, warmup=5)
        # This distinction is material in the released data and must not be
        # hidden by reporting the ceiled query as the published Table V bound.
        self.assertGreater(actual["joint_coverage_pct"] - continuous["joint_coverage_pct"], 1.0)


